import { ChangeDetectionStrategy, Component, computed, inject, signal } from '@angular/core';
import { FormGroup, NonNullableFormBuilder, ReactiveFormsModule, Validators } from '@angular/forms';
import { DomSanitizer, SafeHtml } from '@angular/platform-browser';
import { Observable, forkJoin, switchMap } from 'rxjs';

import { AuthApi } from '../../core/auth/auth.api';
import { SessionStore } from '../../core/auth/session.store';
import { applyProblemToForm, toProblem } from '../../core/bff/problem';
import { FieldError } from '../../shared/ui/field-error';
import { Icon } from '../../shared/ui/icon';

type Step = 'idle' | 'confirm-password' | 'setup' | 'recovery-codes';

/**
 * TOTP two-factor management via Fortify (spec §2.4, SYS-01). Sensitive actions require a
 * recent password confirmation; the server answers 423 and we prompt, then resume the action.
 */
@Component({
  selector: 'pms-two-factor-settings',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [ReactiveFormsModule, FieldError, Icon],
  templateUrl: './two-factor-settings.html',
})
export class TwoFactorSettings {
  private readonly fb = inject(NonNullableFormBuilder);
  private readonly authApi = inject(AuthApi);
  private readonly session = inject(SessionStore);
  private readonly sanitizer = inject(DomSanitizer);

  protected readonly enabled = computed(() => this.session.user()?.two_factor_enabled ?? false);
  protected readonly step = signal<Step>('idle');
  protected readonly busy = signal(false);
  protected readonly error = signal<string | null>(null);
  protected readonly qrCode = signal<SafeHtml | null>(null);
  protected readonly secretKey = signal<string | null>(null);
  protected readonly recoveryCodes = signal<string[]>([]);

  protected readonly passwordForm = this.fb.group({ password: ['', [Validators.required]] });
  protected readonly codeForm = this.fb.group({ code: ['', [Validators.required, Validators.pattern(/^\d{6}$/)]] });

  private resumeAfterConfirmation: (() => void) | null = null;

  protected enable(): void {
    this.run(
      () =>
        this.authApi
          .enableTwoFactor()
          .pipe(switchMap(() => forkJoin({ qr: this.authApi.twoFactorQrCode(), key: this.authApi.twoFactorSecretKey() }))),
      ({ qr, key }) => {
        // The SVG is generated by our own server (Fortify), so it is trusted markup.
        this.qrCode.set(this.sanitizer.bypassSecurityTrustHtml(qr.svg));
        this.secretKey.set(key);
        this.codeForm.reset();
        this.step.set('setup');
      },
    );
  }

  protected confirmSetup(): void {
    if (this.codeForm.invalid) {
      this.codeForm.markAllAsTouched();
      return;
    }

    this.run(
      () =>
        this.authApi
          .confirmTwoFactor(this.codeForm.getRawValue().code)
          .pipe(switchMap(() => this.authApi.recoveryCodes())),
      (codes) => {
        this.session.setTwoFactorEnabled(true);
        this.recoveryCodes.set(codes);
        this.qrCode.set(null);
        this.secretKey.set(null);
        this.step.set('recovery-codes');
      },
      this.codeForm,
    );
  }

  protected showRecoveryCodes(): void {
    this.run(
      () => this.authApi.recoveryCodes(),
      (codes) => {
        this.recoveryCodes.set(codes);
        this.step.set('recovery-codes');
      },
    );
  }

  protected regenerateRecoveryCodes(): void {
    this.run(
      () => this.authApi.regenerateRecoveryCodes().pipe(switchMap(() => this.authApi.recoveryCodes())),
      (codes) => this.recoveryCodes.set(codes),
    );
  }

  protected disable(): void {
    this.run(
      () => this.authApi.disableTwoFactor(),
      () => {
        this.session.setTwoFactorEnabled(false);
        this.recoveryCodes.set([]);
        this.step.set('idle');
      },
    );
  }

  protected confirmPassword(): void {
    if (this.passwordForm.invalid) {
      this.passwordForm.markAllAsTouched();
      return;
    }

    this.busy.set(true);
    this.authApi.confirmPassword(this.passwordForm.getRawValue().password).subscribe({
      next: () => {
        this.busy.set(false);
        this.passwordForm.reset();
        this.step.set('idle');
        const resume = this.resumeAfterConfirmation;
        this.resumeAfterConfirmation = null;
        resume?.();
      },
      error: (error: unknown) => {
        this.busy.set(false);
        this.error.set(applyProblemToForm(this.passwordForm, toProblem(error)));
      },
    });
  }

  protected cancel(): void {
    this.resumeAfterConfirmation = null;
    this.qrCode.set(null);
    this.secretKey.set(null);
    this.passwordForm.reset();
    this.error.set(null);
    this.step.set('idle');
  }

  private run<T>(operation: () => Observable<T>, onSuccess: (value: T) => void, form?: FormGroup): void {
    this.busy.set(true);
    this.error.set(null);

    operation().subscribe({
      next: (value) => {
        this.busy.set(false);
        onSuccess(value);
      },
      error: (error: unknown) => {
        this.busy.set(false);
        const problem = toProblem(error);

        if (problem.status === 423) {
          this.resumeAfterConfirmation = () => this.run(operation, onSuccess, form);
          this.step.set('confirm-password');
          return;
        }

        this.error.set(form ? applyProblemToForm(form, problem) : (problem.detail ?? problem.title));
      },
    });
  }
}
